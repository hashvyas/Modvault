"""Deterministic seed generator for ModVault.

Reads curated YAML data from data/curated/ and cached raw Nexus API JSON
from data/raw/ to generate database/seed.sql and database/seed_expectations.sql.

Usage:
    python scripts/nexus/generate_seed.py
"""

import json
import re
import sys
import uuid
from pathlib import Path
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CURATED_DIR = REPO_ROOT / "data" / "curated"
RAW_DIR = REPO_ROOT / "data" / "raw"
DATABASE_DIR = REPO_ROOT / "database"


def gen_uuid(kind: str, key: str) -> str:
    """Generate a deterministic UUIDv5 in the modvault namespace."""
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"modvault:{kind}:{key}"))


def sql_str(val) -> str:
    """Escape and quote a SQL string literal, or return NULL."""
    if val is None:
        return "NULL"
    escaped = str(val).replace("'", "''")
    return f"'{escaped}'"


def strip_html_bbcode(text: str) -> str:
    """Remove HTML tags, BBCode tags, and clean up excess whitespace."""
    if not text:
        return ""
    # Remove HTML tags
    clean = re.sub(r"<[^>]+>", " ", text)
    # Remove BBCode tags like [b]...[/b], [url=...]...[/url]
    clean = re.sub(r"\[/?[a-zA-Z0-9_-]+(?:=[^\]]+)?\]", " ", clean)
    # Replace multiple spaces / newlines
    clean = re.sub(r"[ \t]+", " ", clean)
    clean = re.sub(r"\n\s*\n+", "\n\n", clean)
    return clean.strip()


def main():
    print("Generating seed.sql and seed_expectations.sql...")

    # 1. Load curated YAML files
    with open(CURATED_DIR / "games.yaml", encoding="utf-8") as f:
        games_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "mods.yaml", encoding="utf-8") as f:
        mods_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "users.yaml", encoding="utf-8") as f:
        users_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "tags.yaml", encoding="utf-8") as f:
        tags_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "dependencies.yaml", encoding="utf-8") as f:
        dependencies_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "compat.yaml", encoding="utf-8") as f:
        compat_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "reviews.yaml", encoding="utf-8") as f:
        reviews_yaml = yaml.safe_load(f)
    with open(CURATED_DIR / "loadouts.yaml", encoding="utf-8") as f:
        loadouts_yaml = yaml.safe_load(f)

    mods_by_ref = {m["ref"]: m for m in mods_yaml}

    # 2. Check that data/raw has needed files
    for g in games_yaml:
        domain = g["domain"]
        game_raw = RAW_DIR / domain / "game.json"
        if not game_raw.is_file():
            print(f"ERROR: Missing {game_raw}. Please run scripts/nexus/pull.py first.", file=sys.stderr)
            sys.exit(1)

    lines = [
        "-- =============================================================================",
        "-- ModVault: Generated Seed Data",
        "-- Auto-generated by scripts/nexus/generate_seed.py. DO NOT EDIT BY HAND.",
        "-- =============================================================================",
        "SET client_encoding = 'UTF8';",
        "",
        "BEGIN;",
        "",
    ]

    # SECTION 1: GAMES
    lines.append("-- 1. GAMES")
    game_id_by_domain = {}
    categories_by_domain = {}

    for g_cfg in games_yaml:
        domain = g_cfg["domain"]
        with open(RAW_DIR / domain / "game.json", encoding="utf-8") as f:
            raw_game = json.load(f)

        g_id = gen_uuid("game", domain)
        game_id_by_domain[domain] = g_id
        categories_by_domain[domain] = {
            c["category_id"]: c["name"] for c in raw_game.get("categories", [])
        }

        name = raw_game.get("name", domain)
        nexus_game_id = str(raw_game.get("id", ""))
        current_version = g_cfg.get("current_version", "")

        lines.append(
            f"INSERT INTO games (game_id, name, domain, nexus_game_id, current_version) VALUES ("
            f"{sql_str(g_id)}, {sql_str(name)}, {sql_str(domain)}, {sql_str(nexus_game_id)}, {sql_str(current_version)}"
            f") ON CONFLICT (domain) DO UPDATE SET current_version = EXCLUDED.current_version;"
        )
    lines.append("")

    # SECTION 2: USERS
    lines.append("-- 2. USERS")
    user_id_by_username = {}
    for u in users_yaml:
        username = u["username"]
        u_id = gen_uuid("user", username)
        user_id_by_username[username] = u_id
        email = u["email"]
        role = u["role"]
        pw = u["password"]

        lines.append(
            f"INSERT INTO users (user_id, username, email, password_hash, role, is_active) VALUES ("
            f"{sql_str(u_id)}, {sql_str(username)}, {sql_str(email)}, "
            f"crypt({sql_str(pw)}, gen_salt('bf', 10)), {sql_str(role)}::user_role_enum, TRUE"
            f") ON CONFLICT (username) DO NOTHING;"
        )
    lines.append("")

    # SECTION 3: TAGS
    lines.append("-- 3. TAGS")
    tag_id_by_slug = {}
    for t in tags_yaml:
        slug = t["slug"]
        t_id = gen_uuid("tag", slug)
        tag_id_by_slug[slug] = t_id
        name = t["name"]

        lines.append(
            f"INSERT INTO tags (tag_id, name, slug) VALUES ("
            f"{sql_str(t_id)}, {sql_str(name)}, {sql_str(slug)}"
            f") ON CONFLICT (slug) DO NOTHING;"
        )
    lines.append("")

    # SECTION 4: MODS
    lines.append("-- 4. MODS")
    mod_id_by_ref = {}
    # Featured mods highlight
    featured_refs = {
        "skyrimspecialedition:12604",
        "skyrimspecialedition:266",
        "fallout4:4598",
        "fallout4:21497",
        "stardewvalley:2400",
        "stardewvalley:1915",
    }

    for m_cfg in mods_yaml:
        ref = m_cfg["ref"]
        domain, nexus_mod_id = ref.split(":", 1)
        m_id = gen_uuid("mod", ref)
        mod_id_by_ref[ref] = m_id
        g_id = game_id_by_domain[domain]

        with open(RAW_DIR / domain / f"mod_{nexus_mod_id}.json", encoding="utf-8") as f:
            raw_mod = json.load(f)

        name = raw_mod.get("name", m_cfg.get("expect_name", ""))
        summary = strip_html_bbcode(raw_mod.get("summary", ""))
        nexus_author = raw_mod.get("author", "")
        downloads = max(0, int(raw_mod.get("mod_downloads", 0)))
        endorsements = max(0, int(raw_mod.get("endorsement_count", 0)))
        cat_id = raw_mod.get("category_id")
        category = categories_by_domain[domain].get(cat_id, "General")
        is_featured = "TRUE" if ref in featured_refs else "FALSE"

        lines.append(
            f"INSERT INTO mods (mod_id, author_id, nexus_author, game_id, nexus_mod_id, name, summary, category, "
            f"download_count, endorsement_count, is_featured, rating_avg, rating_count, embedding) VALUES ("
            f"{sql_str(m_id)}, NULL, {sql_str(nexus_author)}, {sql_str(g_id)}, {sql_str(nexus_mod_id)}, "
            f"{sql_str(name)}, {sql_str(summary)}, {sql_str(category)}, {downloads}, {endorsements}, {is_featured}, 0, 0, NULL"
            f") ON CONFLICT (game_id, nexus_mod_id) DO NOTHING;"
        )
    lines.append("")

    # SECTION 5: MOD VERSIONS
    lines.append("-- 5. MOD VERSIONS")
    version_id_by_ref_semver = {}
    primary_version_by_ref = {}
    versions_by_mod_ref = {}

    for m_cfg in mods_yaml:
        ref = m_cfg["ref"]
        domain, nexus_mod_id = ref.split(":", 1)
        m_id = mod_id_by_ref[ref]

        with open(RAW_DIR / domain / f"files_{nexus_mod_id}.json", encoding="utf-8") as f:
            raw_files = json.load(f)

        files_list = raw_files.get("files", [])
        # Filter files: category_name in MAIN or OLD_VERSION
        eligible_files = [
            f
            for f in files_list
            if str(f.get("category_name", "")).upper() in ("MAIN", "OLD_VERSION")
        ]

        if not eligible_files:
            # Fallback to any file if no MAIN or OLD_VERSION
            eligible_files = files_list[:1] if files_list else []

        # Group by semver (newest uploaded_timestamp wins)
        files_by_semver = {}
        for file_entry in sorted(eligible_files, key=lambda x: int(x.get("uploaded_timestamp", 0)), reverse=True):
            semver = str(file_entry.get("version", "")).strip() or "0.0.0"
            semver = semver[:20]
            if semver not in files_by_semver:
                files_by_semver[semver] = file_entry

        # Pick primary version: newest MAIN file, or newest file overall
        main_files = [f for f in eligible_files if str(f.get("category_name", "")).upper() == "MAIN"]
        if main_files:
            newest_main = max(main_files, key=lambda x: int(x.get("uploaded_timestamp", 0)))
            primary_semver = (str(newest_main.get("version", "")).strip() or "0.0.0")[:20]
        elif files_by_semver:
            primary_semver = next(iter(files_by_semver.keys()))
        else:
            primary_semver = "1.0.0"
            files_by_semver["1.0.0"] = {"file_id": 1, "uploaded_timestamp": 1500000000, "description": "Release"}

        # Emit mod_versions
        versions_by_mod_ref[ref] = []
        yaml_supported = m_cfg.get("supported_game_versions", {}) or {}

        for semver, f_info in files_by_semver.items():
            v_id = gen_uuid("version", f"{ref}@{semver}")
            version_id_by_ref_semver[f"{ref}@{semver}"] = v_id
            versions_by_mod_ref[ref].append(v_id)

            nexus_version_id = str(f_info.get("file_id", ""))
            changelog = strip_html_bbcode(f_info.get("description", ""))
            is_primary = "TRUE" if semver == primary_semver else "FALSE"
            if is_primary == "TRUE":
                primary_version_by_ref[ref] = v_id

            # supported_game_versions TEXT[]
            sup_versions = yaml_supported.get(semver, [])
            if sup_versions:
                sup_array_sql = "ARRAY[" + ", ".join(sql_str(v) for v in sup_versions) + "]::TEXT[]"
            else:
                sup_array_sql = "'{}'::TEXT[]"

            ts = int(f_info.get("uploaded_timestamp", 1500000000))

            lines.append(
                f"INSERT INTO mod_versions (version_id, mod_id, semver, nexus_version_id, changelog, "
                f"supported_game_versions, is_primary, uploaded_at) VALUES ("
                f"{sql_str(v_id)}, {sql_str(m_id)}, {sql_str(semver)}, {sql_str(nexus_version_id)}, {sql_str(changelog)}, "
                f"{sup_array_sql}, {is_primary}, to_timestamp({ts})"
                f") ON CONFLICT (mod_id, semver) DO NOTHING;"
            )

        if ref not in primary_version_by_ref and versions_by_mod_ref[ref]:
            primary_version_by_ref[ref] = versions_by_mod_ref[ref][0]
    lines.append("")

    # SECTION 6: MOD TAGS
    lines.append("-- 6. MOD TAGS")
    for t in tags_yaml:
        t_id = tag_id_by_slug[t["slug"]]
        for mod_ref in t["mods"]:
            m_id = mod_id_by_ref[mod_ref]
            lines.append(
                f"INSERT INTO mod_tags (mod_id, tag_id) VALUES ({sql_str(m_id)}, {sql_str(t_id)}) "
                f"ON CONFLICT DO NOTHING;"
            )
    lines.append("")

    # SECTION 7: MOD DEPENDENCIES
    lines.append("-- 7. MOD DEPENDENCIES")
    for dep in dependencies_yaml:
        mod_ref = dep["mod"]
        req_ref = dep["requires"]
        dep_type = dep.get("type", "required")
        source = dep.get("source", "manual")
        constraint = dep.get("constraint")

        req_mod_id = mod_id_by_ref[req_ref]
        # Applies to every version of mod_ref
        for v_id in versions_by_mod_ref.get(mod_ref, []):
            d_id = gen_uuid("dep", f"{v_id}:{req_mod_id}:{dep_type}")
            lines.append(
                f"INSERT INTO mod_dependencies (dep_id, dependent_version_id, required_mod_id, version_constraint, dep_type, source) VALUES ("
                f"{sql_str(d_id)}, {sql_str(v_id)}, {sql_str(req_mod_id)}, "
                f"{sql_str(constraint)}, {sql_str(dep_type)}::dep_type_enum, {sql_str(source)}::dep_source_enum"
                f") ON CONFLICT (dependent_version_id, required_mod_id) DO NOTHING;"
            )
    lines.append("")

    # SECTION 8: COMPATIBILITY MATRIX
    lines.append("-- 8. COMPATIBILITY MATRIX")
    for cmp in compat_yaml:
        ref_a = cmp["a"]
        ref_b = cmp["b"]
        a_semver = cmp.get("a_semver")
        b_semver = cmp.get("b_semver")

        v_a = version_id_by_ref_semver.get(f"{ref_a}@{a_semver}") if a_semver else primary_version_by_ref[ref_a]
        v_b = version_id_by_ref_semver.get(f"{ref_b}@{b_semver}") if b_semver else primary_version_by_ref[ref_b]

        # Enforce canonical order (v_a < v_b)
        if v_a > v_b:
            v_a, v_b = v_b, v_a

        c_id = gen_uuid("matrix", f"{v_a}:{v_b}")
        status = cmp["status"]
        detail = cmp.get("detail")
        detail_sql = f"{sql_str(json.dumps(detail))}::jsonb" if detail else "NULL"
        verifier = cmp.get("verified_by")
        verifier_id = user_id_by_username.get(verifier) if verifier else None

        lines.append(
            f"INSERT INTO compatibility_matrix (compat_id, version_a_id, version_b_id, status, conflict_detail, verified_by) VALUES ("
            f"{sql_str(c_id)}, {sql_str(v_a)}, {sql_str(v_b)}, {sql_str(status)}::compat_status_enum, {detail_sql}, {sql_str(verifier_id)}"
            f") ON CONFLICT (version_a_id, version_b_id) DO NOTHING;"
        )
    lines.append("")

    # SECTION 9: REVIEWS
    lines.append("-- 9. REVIEWS")
    for r in reviews_yaml:
        username = r["user"]
        mod_ref = r["mod"]
        u_id = user_id_by_username[username]
        m_id = mod_id_by_ref[mod_ref]
        r_id = gen_uuid("review", f"{u_id}:{m_id}")
        rating = int(r["rating"])
        body = r.get("body", "")

        lines.append(
            f"INSERT INTO reviews (review_id, user_id, mod_id, rating, body) VALUES ("
            f"{sql_str(r_id)}, {sql_str(u_id)}, {sql_str(m_id)}, {rating}, {sql_str(body)}"
            f") ON CONFLICT (user_id, mod_id) DO NOTHING;"
        )
    lines.append("")

    # SECTION 10: LOADOUTS & LOADOUT_MODS
    lines.append("-- 10. LOADOUTS & LOADOUT_MODS")
    for ld in loadouts_yaml:
        name = ld["name"]
        username = ld["owner"]
        domain = ld["game"]
        u_id = user_id_by_username[username]
        g_id = game_id_by_domain[domain]
        ld_id = gen_uuid("loadout", f"{u_id}:{name}")

        desc = ld.get("description", "")
        game_version = ld.get("game_version")
        is_public = "TRUE" if ld.get("is_public", False) else "FALSE"

        lines.append(
            f"INSERT INTO loadouts (loadout_id, user_id, game_id, name, description, game_version, is_public) VALUES ("
            f"{sql_str(ld_id)}, {sql_str(u_id)}, {sql_str(g_id)}, {sql_str(name)}, {sql_str(desc)}, {sql_str(game_version)}, {is_public}"
            f") ON CONFLICT DO NOTHING;"
        )

        pos = 0
        for m_item in ld.get("mods", []):
            if "@" in m_item:
                ref, semver = m_item.split("@", 1)
                v_id = version_id_by_ref_semver[f"{ref}@{semver}"]
            else:
                ref = m_item
                v_id = primary_version_by_ref[ref]

            lm_id = gen_uuid("loadout_mod", f"{ld_id}:{v_id}")
            lines.append(
                f"INSERT INTO loadout_mods (id, loadout_id, version_id, position, enabled) VALUES ("
                f"{sql_str(lm_id)}, {sql_str(ld_id)}, {sql_str(v_id)}, {pos}, TRUE"
                f") ON CONFLICT (loadout_id, version_id) DO NOTHING;"
            )
            pos += 1

        for m_item in ld.get("disabled", []):
            if "@" in m_item:
                ref, semver = m_item.split("@", 1)
                v_id = version_id_by_ref_semver[f"{ref}@{semver}"]
            else:
                ref = m_item
                v_id = primary_version_by_ref[ref]

            lm_id = gen_uuid("loadout_mod", f"{ld_id}:{v_id}")
            lines.append(
                f"INSERT INTO loadout_mods (id, loadout_id, version_id, position, enabled) VALUES ("
                f"{sql_str(lm_id)}, {sql_str(ld_id)}, {sql_str(v_id)}, {pos}, FALSE"
                f") ON CONFLICT (loadout_id, version_id) DO NOTHING;"
            )
            pos += 1

    lines.append("")
    lines.append("COMMIT;")
    lines.append("")

    # Write seed.sql
    seed_sql_path = DATABASE_DIR / "seed.sql"
    with open(seed_sql_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {seed_sql_path}")

    # Write seed_expectations.sql
    expectations_lines = [
        "-- =============================================================================",
        "-- ModVault: Seed Verification and Health Expectations",
        "-- Auto-generated by scripts/nexus/generate_seed.py. Runs after Sync 2.",
        "-- =============================================================================",
        "SET client_encoding = 'UTF8';",
        "",
        "DO $$",
        "DECLARE",
        "    v_status text;",
        "    v_cnt bigint;",
        "BEGIN",
        "    -- 1. Table row count assertions",
        "    SELECT count(*) INTO v_cnt FROM games;",
        f"    ASSERT v_cnt = {len(games_yaml)}, 'Expected {len(games_yaml)} games, got ' || v_cnt;",
        "",
        "    SELECT count(*) INTO v_cnt FROM users;",
        f"    ASSERT v_cnt = {len(users_yaml)}, 'Expected {len(users_yaml)} users, got ' || v_cnt;",
        "",
        "    SELECT count(*) INTO v_cnt FROM tags;",
        f"    ASSERT v_cnt = {len(tags_yaml)}, 'Expected {len(tags_yaml)} tags, got ' || v_cnt;",
        "",
        "    SELECT count(*) INTO v_cnt FROM mods;",
        f"    ASSERT v_cnt = {len(mods_yaml)}, 'Expected {len(mods_yaml)} mods, got ' || v_cnt;",
        "",
        "    SELECT count(*) INTO v_cnt FROM reviews;",
        f"    ASSERT v_cnt = {len(reviews_yaml)}, 'Expected {len(reviews_yaml)} reviews, got ' || v_cnt;",
        "",
        "    SELECT count(*) INTO v_cnt FROM loadouts;",
        f"    ASSERT v_cnt = {len(loadouts_yaml)}, 'Expected {len(loadouts_yaml)} loadouts, got ' || v_cnt;",
        "",
        "    -- 2. Loadout health status expectations (requires P1 functions from Sync 2)",
    ]

    for ld in loadouts_yaml:
        name = ld["name"]
        expected_status = ld["expected_status"]
        username = ld["owner"]
        u_id = user_id_by_username[username]
        ld_id = gen_uuid("loadout", f"{u_id}:{name}")

        expectations_lines.extend([
            f"    SELECT status INTO v_status FROM loadout_health_view WHERE loadout_id = '{ld_id}'::uuid;",
            f"    ASSERT v_status = '{expected_status}', 'Loadout \"{name}\" status expected {expected_status}, got ' || coalesce(v_status, 'NULL');",
        ])

    expectations_lines.extend([
        "",
        "    RAISE NOTICE 'seed_expectations: all assertions passed successfully.';",
        "END $$;",
        "",
    ])

    expect_path = DATABASE_DIR / "seed_expectations.sql"
    with open(expect_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(expectations_lines))
    print(f"Wrote {expect_path}")


if __name__ == "__main__":
    main()
